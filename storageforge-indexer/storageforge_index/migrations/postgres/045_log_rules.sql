-- StorageForge schema v45 · postgres: log rules (logrules.py). A rule matches lines as they arrive and is one more source of alerts.
-- host, unit, program and text are patterns with * for anything; none of them is a regular expression. builtin: the key of a rule that ships
-- with StorageForge, whose text is its own and whose threshold, window, level and enabled are the operator's to change.
CREATE TABLE log_rules (
    rule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT    NOT NULL UNIQUE,
    builtin     TEXT    UNIQUE,
    host        TEXT    NOT NULL DEFAULT '*',
    unit        TEXT    NOT NULL DEFAULT '*',
    program     TEXT    NOT NULL DEFAULT '*',
    min_level   INTEGER NOT NULL DEFAULT 7,
    text        TEXT    NOT NULL DEFAULT '*',
    threshold   INTEGER NOT NULL DEFAULT 1,
    window_secs INTEGER NOT NULL DEFAULT 3600,
    level       TEXT    NOT NULL DEFAULT 'warn',
    enabled     INTEGER NOT NULL DEFAULT 1,
    note        TEXT    NOT NULL DEFAULT '',
    updated_by  TEXT    NOT NULL DEFAULT 'storageforge',
    updated_at  BIGINT  NOT NULL
);

-- matches per rule, host and 5 minutes, by when the line arrived: a host's clock cannot move a match out of a rule's window.
-- sample: the newest line that matched, so the alert can say what it saw.
CREATE TABLE log_rule_hits (
    rule_id BIGINT  NOT NULL,
    host    TEXT    NOT NULL,
    bucket  BIGINT  NOT NULL,
    hits    INTEGER NOT NULL,
    sample  TEXT    NOT NULL DEFAULT '',
    PRIMARY KEY (rule_id, host, bucket)
);
CREATE INDEX log_rule_hits_bucket ON log_rule_hits (bucket);

