-- StorageForge schema v37 · postgres: passwords for network devices that take no SSH key, such as Telnet-only switches. Sealed as keys are.
CREATE TABLE device_credentials (
    credential_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cred_uuid      TEXT    NOT NULL UNIQUE,
    name           TEXT    NOT NULL UNIQUE,
    username       TEXT,
    dek_nonce      BYTEA   NOT NULL,
    wrapped_dek    BYTEA   NOT NULL,
    nonce          BYTEA   NOT NULL,
    ciphertext     BYTEA   NOT NULL,               -- JSON: the password and any enable password
    created_at     BIGINT  NOT NULL,
    rotated_at     BIGINT
);

INSERT INTO schema_version (version, name, applied_at)
VALUES (37, 'device_credentials', EXTRACT(EPOCH FROM now())::BIGINT);
