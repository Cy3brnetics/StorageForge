-- StorageForge schema v36 · postgres: the operator's own security policy, and the history behind trends and bans.
CREATE TABLE security_waivers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host        TEXT    NOT NULL,          -- a host, or * for all of them
    finding     TEXT    NOT NULL,          -- a compliance check id or a Lynis finding id
    reason      TEXT    NOT NULL,
    approver    TEXT    NOT NULL,
    expires_at  BIGINT,
    created_at  BIGINT  NOT NULL,
    UNIQUE (host, finding)
);

CREATE TABLE security_profiles (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT    NOT NULL UNIQUE,
    base           TEXT    NOT NULL,
    overrides_json TEXT    NOT NULL DEFAULT '{}',
    created_by     TEXT,
    updated_at     BIGINT  NOT NULL
);

CREATE TABLE security_retention_policies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host        TEXT    NOT NULL,          -- a host, or * for all of them
    pattern     TEXT    NOT NULL,          -- a glob on the dataset or mount path
    days        INTEGER NOT NULL,
    legal       INTEGER NOT NULL DEFAULT 0,
    auto        INTEGER NOT NULL DEFAULT 0,
    created_by  TEXT,
    updated_at  BIGINT  NOT NULL
);

CREATE TABLE security_playbooks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT    NOT NULL UNIQUE,
    trigger_kind    TEXT    NOT NULL,
    conditions_json TEXT    NOT NULL DEFAULT '{}',
    actions_json    TEXT    NOT NULL DEFAULT '[]',
    enabled         INTEGER NOT NULL DEFAULT 1,
    dry_run         INTEGER NOT NULL DEFAULT 1,
    created_by      TEXT,
    updated_at      BIGINT  NOT NULL
);

-- What each playbook did, or would have, for each event. pending: waiting for someone to confirm it.
CREATE TABLE security_playbook_runs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playbook_id BIGINT  NOT NULL,
    event_id    BIGINT,
    host        TEXT    NOT NULL,
    at          BIGINT  NOT NULL,
    outcome     TEXT    NOT NULL CHECK (outcome IN ('would', 'pending', 'ran', 'failed', 'dismissed')),
    detail_json TEXT    NOT NULL DEFAULT '{}'
);
CREATE INDEX ix_security_playbook_runs_at ON security_playbook_runs (at);

CREATE TABLE security_yara_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT    NOT NULL UNIQUE,
    body        TEXT    NOT NULL,
    enabled     INTEGER NOT NULL DEFAULT 1,
    created_by  TEXT,
    updated_at  BIGINT  NOT NULL
);

CREATE TABLE security_dashboards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner       TEXT    NOT NULL,
    name        TEXT    NOT NULL,
    layout_json TEXT    NOT NULL DEFAULT '[]',
    updated_at  BIGINT  NOT NULL,
    UNIQUE (owner, name)
);

-- A number over time: the hardening index, checks passing. Rebuilt going forward by measurements.
CREATE TABLE security_readings (
    host        TEXT    NOT NULL,
    kind        TEXT    NOT NULL,
    at          BIGINT  NOT NULL,
    value       DOUBLE PRECISION,
    detail_json TEXT    NOT NULL DEFAULT '{}',
    PRIMARY KEY (host, kind, at)
);

-- Who has been dropped before, so a repeat offender goes up a tier.
CREATE TABLE security_ban_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host        TEXT    NOT NULL,
    ip_address  TEXT    NOT NULL,
    tier        INTEGER NOT NULL,
    at          BIGINT  NOT NULL,
    reason      TEXT    NOT NULL DEFAULT ''
);
CREATE INDEX ix_security_ban_history_ip ON security_ban_history (ip_address, at);

-- FIDO2 keys for stepping up before a release. Public keys only: the private half never leaves the token.
CREATE TABLE security_webauthn (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        TEXT    NOT NULL,
    credential_id   TEXT    NOT NULL UNIQUE,
    public_key      TEXT    NOT NULL,
    sign_count      BIGINT  NOT NULL DEFAULT 0,
    name            TEXT    NOT NULL DEFAULT '',
    created_at      BIGINT  NOT NULL
);
CREATE INDEX ix_security_webauthn_user ON security_webauthn (username);

